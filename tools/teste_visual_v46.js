  await page.evaluate(k=>window.__dl(k,'ok',1),key);
  await page.waitForFunction(k=>{const e=document.querySelector('#bp .rima-v43-fav-row[data-key="'+k+'"] .rima-v47-fav-download');return !!e&&e.classList.contains('ok')},key,{timeout:7000});
