  const savedLabel=(await row.locator('.rima-v48-fav-status').textContent()||'').trim();
  ok('downloaded favorite shows SALVO NO CELULAR below the beat name',savedLabel.includes('SALVO NO CELULAR'),savedLabel);
  const bpWeight=Number(await page.locator('#bp .rima-v43-toggle').evaluate(e=>getComputedStyle(e).fontWeight));
  ok('Favorites label is not bold in setup selector',bpWeight<=600,String(bpWeight));
  const bpCountWeight=Number(await page.locator('#bp .rima-v43-toggle .rima-v29-count').evaluate(e=>getComputedStyle(e).fontWeight));
